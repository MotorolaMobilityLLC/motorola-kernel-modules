static int load_sram_fw(struct qmrom_handle *handle,
			const struct firmware *sram_fw)
{
	int rc;
	size_t sent = 0;
	const char *bin_data = (const char *)sram_fw->data;
#ifdef CONFIG_FLASHING_STATS
	qmrom_time start_time;
#endif
	LOG_DBG("%s: starting...\n", __func__);
	rc = qmrom_wait_ready(handle);
	if (rc)
		return rc;

	LOG_DBG("%s: sending CMD_LOAD_SRAM:FILE_SIZE command\n", __func__);
	rc = qmrom_write_size_cmd32(
		handle,
		MAKE_CMD_HDR(CMD_LOAD_SRAM, SUB_CMD_LOAD_SRAM_FILE_SIZE,
			     RESP_NONE)
			.all,
		sizeof(uint32_t), (const char *)&sram_fw->size);
	qmrom_poll_cmd_resp(handle);
	if (COMPARE_RSP(&handle->sstc->payload[0], &CMD_LOAD_SRAM_RSP_HDR) !=
	    0) {
		log_error_response(__func__, &CMD_LOAD_SRAM_RSP_HDR,
				   (resp_t *)&handle->sstc->payload[0]);
		return SPI_PROTO_WRONG_RESP;
	}

	while (sent < sram_fw->size) {
		uint32_t tx_bytes = sram_fw->size - sent;
		if (tx_bytes > CHUNK_SIZE)
			tx_bytes = CHUNK_SIZE;

		LOG_DBG("%s: sending CMD_LOAD_SRAM:IMG_DATA command with %" PRIu32
			" bytes\n",
			__func__, tx_bytes);
#ifdef CONFIG_FLASHING_STATS
		start_time = qmrom_time_get();
#endif
		rc = qmrom_write_size_cmd32(
			handle,
			MAKE_CMD_HDR(CMD_LOAD_SRAM, SUB_CMD_LOAD_SRAM_IMG_DATA,
				     RESP_NONE)
				.all,
			tx_bytes, bin_data);
		if (rc)
			return rc;
		sent += tx_bytes;
		bin_data += tx_bytes;
		if (sent == sram_fw->size) {
			LOG_INFO("%s: flashing done, quitting now\n", __func__);
			break;
		}
		qmrom_poll_cmd_resp(handle);
#ifdef CONFIG_FLASHING_STATS
		update_write_stats(start_time, tx_bytes);
#endif
		if (COMPARE_RSP(&handle->sstc->payload[0],
				&CMD_LOAD_SRAM_RSP_HDR) != 0) {
			log_error_response(__func__, &CMD_LOAD_SRAM_RSP_HDR,
					   (resp_t *)&handle->sstc->payload[0]);
			return SPI_PROTO_WRONG_RESP;
		}
	}
#ifdef CONFIG_FLASHING_STATS
	dump_stats();
#endif

	return 0;
}

static void get_enum_tuple(const enum_tuple_t *tuples, uint32_t value,
			   enum_tuple_t *out)
{
	size_t i;

	out->value = value;
	out->name = "UNKNOWN";
	for (i = 0; tuples[i].name != NULL; i++) {
		if (out->value == tuples[i].value) {
			out->name = tuples[i].name;
			break;
		}
	}
}

static void log_error_response(const char *func, resp_t *expected,
			       resp_t *received)
{
#define RSP_HDR_EXP(x)                                                        \
	(x).cmd.name, (x).cmd.value, (x).sub_cmd.name, (x).sub_cmd.value,     \
		(x).resp_code.name, (x).resp_code.value, (x).error_code.name, \
		(x).error_code.value

	response_enum_tuple_t exp, rec;

	get_enum_tuple(cmd_enum_tuples, expected->cmd_hdr.cmd, &exp.cmd);
	get_enum_tuple(expected->cmd_hdr.cmd == CMD_LOAD_SRAM ?
			       sub_cmd_load_sram_enum_tuples :
			       sub_cmd_load_fw_pkg_enum_tuples,
		       expected->cmd_hdr.sub_cmd, &exp.sub_cmd);
	get_enum_tuple(resp_code_enum_tuples, expected->cmd_hdr.resp,
		       &exp.resp_code);
	get_enum_tuple(error_code_enum_tuples, expected->err_code,
		       &exp.error_code);

	get_enum_tuple(cmd_enum_tuples, received->cmd_hdr.cmd, &rec.cmd);
	get_enum_tuple(received->cmd_hdr.cmd == CMD_LOAD_SRAM ?
			       sub_cmd_load_sram_enum_tuples :
			       sub_cmd_load_fw_pkg_enum_tuples,
		       received->cmd_hdr.sub_cmd, &rec.sub_cmd);
	get_enum_tuple(resp_code_enum_tuples, received->cmd_hdr.resp,
		       &rec.resp_code);
	get_enum_tuple(error_code_enum_tuples, received->err_code,
		       &rec.error_code);

	LOG_ERR("%s: Expected: %s(%#x), %s(%#x), %s(%#x), %s(%#x)"
		" Received: %s(%#x), %s(%#x), %s(%#x), %s(%#x)\n",
		func, RSP_HDR_EXP(exp), RSP_HDR_EXP(rec));
}

