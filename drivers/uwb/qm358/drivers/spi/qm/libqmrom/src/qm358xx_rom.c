/*! Command header structure typedef. */
typedef struct {
	union {
		struct {
			/*! Command code. */
			uint8_t cmd;
			/*! Sub-command code. */
			uint8_t sub_cmd;
			/*! Response code. */
			uint16_t resp;
		};
		uint32_t all;
	};
} cmd_hdr_t;

#define MAKE_CMD_HDR(c, sc, r)                           \
	(cmd_hdr_t)                                      \
	{                                                \
		.cmd = (c), .sub_cmd = (sc), .resp = (r) \
	}

/*! Response header structure typedef. */
typedef struct {
	/*! Command header. */
	cmd_hdr_t cmd_hdr;
	/*! Error code. */
	uint32_t err_code;
} resp_t;

#define MAKE_RSP_HDR(ch, ec)                      \
	(resp_t)                                  \
	{                                         \
		.cmd_hdr = (ch), .err_code = (ec) \
	}

